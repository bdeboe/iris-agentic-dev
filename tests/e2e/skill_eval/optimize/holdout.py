"""The routing train/holdout split (spec 128 FR-003, FR-007).

`sha256(id) mod 100 < 60` puts an item in train, otherwise holdout. The rule decides; the committed
`routing-split.toml` records it so a reviewer can see the holdout, and `load_split` raises when the file
and the rule disagree. An existing assignment therefore cannot move without a test failing, and a new
item lands where the rule puts it.
"""

from __future__ import annotations

import hashlib
import tomllib
from pathlib import Path

TRAIN = "train"
HOLDOUT = "holdout"
TRAIN_PERCENT = 60


class SplitInvalid(ValueError):
    pass


class HoldoutLeak(RuntimeError):
    pass


def assign(item_id: str) -> str:
    n = int(hashlib.sha256(item_id.encode()).hexdigest(), 16) % 100
    return TRAIN if n < TRAIN_PERCENT else HOLDOUT


def render_split(ids) -> str:
    parts = [
        "# Spec 128 routing split. Generated by holdout.render_split; the hash rule decides.\n"
    ]
    for side in (TRAIN, HOLDOUT):
        chosen = sorted(i for i in ids if assign(i) == side)
        parts.append(
            f"\n[{side}]\nids = [\n" + "".join(f'  "{i}",\n' for i in chosen) + "]\n"
        )
    return "".join(parts)


def load_split(path) -> dict[str, str]:
    doc = tomllib.loads(Path(path).read_text())
    split: dict[str, str] = {}
    for side in (TRAIN, HOLDOUT):
        for i in doc.get(side, {}).get("ids", []):
            if i in split:
                raise SplitInvalid(f"{i} is listed in both train and holdout")
            if assign(i) != side:
                raise SplitInvalid(
                    f"{i} is listed in {side}, but the hash rule puts it in {assign(i)}"
                )
            split[i] = side
    return split


def _only(items, split, side):
    for it in items:
        got = split.get(it["id"])
        if got != side:
            raise HoldoutLeak(
                f"{it['id']} is {got or 'not in the split'}, expected {side} only"
            )
    return list(items)


def train_only(items, split):
    return _only(items, split, TRAIN)


def holdout_only(items, split):
    return _only(items, split, HOLDOUT)
